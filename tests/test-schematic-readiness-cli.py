"""Opt-in complete native/Blender composition checks for owned mechanical benches.

Inputs are generated by Schematic.Tests --write-readiness-fixtures, then exercised
through the same actual bounded public CLI lifecycle as the three model examples.
Synthetic complete-design assertions never grant human asset/runtime acceptance.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess
import sys
import tempfile
from schematic_qa_numbers import same_native_numbers

ROOT = Path(__file__).resolve().parents[1]
CASES = ('slider', 'spur-gears', 'rack-pinion', 'pulley-belt', 'slider-crank', 'four-bar', 'hose', 'spring')


def point(value):
    return tuple(value[key] for key in 'xyz')


def distance(first, second):
    return math.dist(point(first), point(second))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--cli', type=Path, default=ROOT/'artifacts/bubo/bubo.dll')
    parser.add_argument('--blender', type=Path, required=True)
    parser.add_argument('--design-directory', type=Path, required=True)
    parser.add_argument('--case', choices=CASES, action='append')
    args = parser.parse_args()
    source = args.design_directory.resolve(strict=True)
    cases = args.case or list(CASES)
    for case in cases:
        assert (source/(case+'.json')).is_file(), case
    parent = ROOT/'.bubo/readiness'; parent.mkdir(parents=True, exist_ok=True)
    evidence = Path(tempfile.mkdtemp(prefix='r-', dir=parent))
    checks = []

    def check(condition, label):
        assert condition, label
        checks.append(label)
        print('PASS:', label, flush=True)

    command = [sys.executable, '-B', '-X', 'utf8', str(ROOT/'tests/test-schematic-assembly-cli.py'),
               '--cli', str(args.cli.resolve(strict=True)), '--blender', str(args.blender.resolve(strict=True)),
               '--design-directory', str(source)]
    for case in cases:
        command += ['--case', case]
    run = subprocess.run(command, cwd=ROOT, capture_output=True, timeout=14_400)
    (evidence/'actual-cli.stdout.log').write_bytes(run.stdout)
    (evidence/'actual-cli.stderr.log').write_bytes(run.stderr)
    record = {'command': command, 'exitCode': run.returncode, 'status': 'failed', 'checks': checks,
              'scope': 'Owned engineering fixtures; actual native compiler, bounded Blender author/reopen, native measured geometry, skin and sampled clearance. No manufacturing, continuous-collision or human/runtime acceptance.'}
    try:
        assert run.returncode == 0, (run.stdout+run.stderr)[-12_000:].decode('utf-8', errors='replace')
        result = json.loads(run.stdout.decode('utf-8').splitlines()[-1])
        summary_path = Path(result['evidence']).resolve(strict=True)
        summary = json.loads(summary_path.read_bytes()); project = Path(summary['project'])
        check(summary['status'] == 'passed', 'every requested bench completed the actual public lifecycle')
        record['lifecycleSummary'] = str(summary_path)
        record['lifecycleSummarySha256'] = hashlib.sha256(summary_path.read_bytes()).hexdigest()
        record['cases'] = {}
        for name in cases:
            case = summary['cases'][name]
            spec = json.loads((project/'inputs'/f'{name}.json').read_bytes())
            status = case['motion']
            report_path = project/status['motionReport']
            report = json.loads(report_path.read_bytes())
            job = json.loads(report_path.parent.parent.joinpath('job.json').read_bytes())
            native = json.loads((project/status['motionNativeVerification']).read_bytes())
            check(same_native_numbers(report, native['report']) and all(p['clearance']['isValid'] for p in native['poses']), name+': actual native measured clearance at every approved sample')
            check(len(native['poses']) == job['plan']['sampling']['totalSamples'], name+': no diagnostic sample omitted')
            joints = {j['id']: j for j in spec['joints']}
            expected_clips = {c['id']: c for c in job['plan']['clips']}
            for clip in report['clips']:
                expected = expected_clips[clip['id']]
                check(len(clip['samples']) == len(expected['samples']), name+': actual range/cycle sampling '+clip['id'])
                for actual, desired in zip(clip['samples'], expected['samples']):
                    measured = {i['instanceId']: i for i in actual['instances']}
                    for joint in joints.values():
                        if joint['kind'] not in ('fixed', 'hinge', 'rotary'):
                            continue
                        parent_port = next(p for p in measured[joint['parentInstanceId']]['ports'] if p['portId'] == joint['parentInterfaceId'])
                        child_port = next(p for p in measured[joint['childInstanceId']]['ports'] if p['portId'] == joint['childInterfaceId'])
                        assert distance(parent_port['worldPose']['origin'], child_port['worldPose']['origin']) <= spec['numerics']['linearTolerance']*2, (name, clip['id'], joint['id'], actual['index'])
                    for instance_id, pose in desired['pose']['instances'].items():
                        # The native verifier also checks bases and deformed vertices. This
                        # explicit comparison binds the actual report to the compiled path.
                        assert distance(measured[instance_id]['worldPose']['origin'], pose['origin']) <= spec['numerics']['linearTolerance'], (name, clip['id'], instance_id, actual['index'])
            check(True, name+': independently reopened component pivots and native compiled transforms agree')
            for mechanism in spec['mechanisms']:
                first, second = mechanism['jointIds'][:2]
                for clip in job['plan']['clips']:
                    for sample in clip['samples']:
                        values = sample['pose']['jointValues']
                        driver = values[first]-joints[first]['rest']
                        follower = values[second]-joints[second]['rest']
                        if mechanism['kind'] in ('spurGears', 'pulleyBelt'):
                            assert abs(follower-driver*mechanism['parameters']['ratio']) < 1e-8
                        elif mechanism['kind'] == 'rackAndPinion':
                            assert abs(follower-math.radians(driver)*mechanism['parameters']['pitchRadius']) < 1e-8
                        else:
                            assert all(c['linearError'] <= spec['numerics']['linearTolerance'] and c['angularErrorDegrees'] <= spec['numerics']['angularToleranceDegrees'] for c in sample['pose']['closures'])
                check(True, name+': explicit '+mechanism['kind']+' driver/follower/closure relation survives actual evaluated poses')
            for route in spec['routes']:
                owner = route['instanceId']; prototype = next(i for i in report['instances'] if i['instanceId'] == owner)
                samples = [next(i for i in s['instances'] if i['instanceId'] == owner) for c in report['clips'] for s in c['samples']]
                check(prototype['rig'] is not None and all(i['rig'] is not None for i in samples), name+': actual owned flexible rig persists in every sample')
                check(any(i['geometrySha256'] != prototype['geometrySha256'] for i in samples), name+': native-generated motion changes actual flexible geometry')
                check(all(any(f['instanceId'] == owner for f in p['flexible']) for p in native['poses']), name+': every actual flexible pose has independent endpoint/bend/stretch metrics')
                if route['closed']:
                    check(any(distance(i['rig']['ringCenters'][0], prototype['rig']['ringCenters'][0]) > .001 for i in samples), name+': closed material rings advance around the actual source path')
            record['cases'][name] = {'motionReport': str(report_path), 'sampling': job['plan']['sampling'],
                'nativeWorkChecks': native['workChecks'], 'mechanisms': [m['kind'] for m in spec['mechanisms']],
                'flexibleKinds': [p['kind'] for p in spec['parts'] if p['kind'] != 'rigid']}
        record['status'] = 'passed'
    finally:
        (evidence/'SUMMARY.json').write_text(json.dumps(record, indent=2)+'\n', encoding='utf-8')
    print(json.dumps({'status': 'passed', 'checks': len(checks), 'evidence': str(evidence/'SUMMARY.json')}), flush=True)


if __name__ == '__main__':
    main()
